-- Bổ sung ghi chú kết quả vào danh sách quản trị để đối chiếu sau cập nhật.
create or replace function public.admin_lay_ket_qua(p_ma_cb text,p_mat_khau text)
returns jsonb language plpgsql security definer set search_path=public as $$ declare r jsonb; begin
 if not public.qlnn_xac_nhan_admin(p_ma_cb,p_mat_khau) then return jsonb_build_object('ok',false,'message','Không có quyền quản trị.'); end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.dot_kiem_tra desc,x.ma_hs,x.mon),'[]'::jsonb) into r from (select ma_hs,dot_kiem_tra,mon,diem,ngay_kiem_tra,loai_kiem_tra,ghi_chu,updated_at from public.ket_qua_kiem_tra order by dot_kiem_tra desc limit 1000) x;
 return jsonb_build_object('ok',true,'rows',r);
end $$;

create or replace function public.admin_lay_phuc_khao(p_ma_cb text,p_mat_khau text)
returns jsonb language plpgsql security definer set search_path=public as $$ declare r jsonb; begin
 if not public.qlnn_xac_nhan_admin(p_ma_cb,p_mat_khau) then return jsonb_build_object('ok',false,'message','Không có quyền quản trị.'); end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) into r from (select p.id,p.ket_qua_id,p.ma_hs,p.ly_do,p.trang_thai,p.phan_hoi,p.created_at,q.mon,q.dot_kiem_tra,q.diem,q.ghi_chu as ghi_chu_ket_qua,q.id as ket_result_id from public.phuc_khao_kiem_tra p join public.ket_qua_kiem_tra q on q.id=p.ket_qua_id order by p.created_at desc limit 1000) x;
 return jsonb_build_object('ok',true,'rows',r);
end $$;
grant execute on function public.admin_lay_ket_qua(text,text) to anon,authenticated;
grant execute on function public.admin_lay_phuc_khao(text,text) to anon,authenticated;
