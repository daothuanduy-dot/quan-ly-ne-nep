create table if not exists public.ket_qua_kiem_tra (
 id bigint generated by default as identity primary key,
 ma_hs varchar not null,
 nam_hoc text not null default '2026-2027',
 dot_kiem_tra text not null,
 loai_kiem_tra text not null default 'Định kỳ',
 mon text not null check (mon in ('Toán','Văn','Tiếng Anh','Vật lý','Hoá học','Sinh học','Lịch Sử','Địa lý','GD KTPL','Tin học')),
 diem numeric(4,2) not null check (diem>=0 and diem<=10),
 ngay_kiem_tra date,
 ghi_chu text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(ma_hs,dot_kiem_tra,mon,nam_hoc)
);
create index if not exists idx_ket_qua_kiem_tra_ma_hs on public.ket_qua_kiem_tra(ma_hs,nam_hoc,dot_kiem_tra);

create table if not exists public.phuc_khao_kiem_tra (
 id bigint generated by default as identity primary key,
 ket_qua_id bigint not null references public.ket_qua_kiem_tra(id) on delete cascade,
 ma_hs varchar not null,
 ly_do text not null,
 trang_thai text not null default 'Đã gửi' check (trang_thai in ('Đã gửi','Đang xem xét','Đã xử lý','Từ chối')),
 phan_hoi text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(ket_qua_id)
);
create index if not exists idx_phuc_khao_ma_hs on public.phuc_khao_kiem_tra(ma_hs,created_at desc);

create or replace function public.login_hoc_sinh(p_ma_hs text,p_mat_khau text,p_vai_tro text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare s public.danh_sach%rowtype;
begin
 if p_vai_tro not in ('parent','student') then return null; end if;
 select * into s from public.danh_sach d where btrim(d.ma_hs)=btrim(p_ma_hs) and btrim(coalesce(d.mat_khau,''))=btrim(coalesce(p_mat_khau,'')) and (d.trang_thai is null or lower(btrim(d.trang_thai)) not in ('inactive','nghi hoc','đã nghỉ','false','0')) limit 1;
 if not found then return null; end if;
 return jsonb_build_object('ma_hs',s.ma_hs,'ho_ten',s.ho_ten,'khoi',s.khoi,'lop',s.lop,'nam_hoc',s.nam_hoc);
end $$;

create or replace function public.portal_lay_du_lieu(p_ma_hs text,p_mat_khau text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare s public.danh_sach%rowtype; r jsonb; n jsonb; a jsonb;
begin
 select * into s from public.danh_sach d where btrim(d.ma_hs)=btrim(p_ma_hs) and btrim(coalesce(d.mat_khau,''))=btrim(coalesce(p_mat_khau,'')) and (d.trang_thai is null or lower(btrim(d.trang_thai)) not in ('inactive','nghi hoc','đã nghỉ','false','0')) limit 1;
 if not found then return null; end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.dot_kiem_tra desc,x.mon), '[]'::jsonb) into r from public.ket_qua_kiem_tra x where x.ma_hs=s.ma_hs;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.ngay_diem_danh desc), '[]'::jsonb) into n from public.diem_danh_master x where x.ma_hs=s.ma_hs;
 select coalesce(jsonb_agg(to_jsonb(p)||jsonb_build_object('mon',q.mon,'dot_kiem_tra',q.dot_kiem_tra) order by p.created_at desc), '[]'::jsonb) into a from public.phuc_khao_kiem_tra p join public.ket_qua_kiem_tra q on q.id=p.ket_qua_id where p.ma_hs=s.ma_hs;
 return jsonb_build_object('hoc_sinh',jsonb_build_object('ma_hs',s.ma_hs,'ho_ten',s.ho_ten,'khoi',s.khoi,'lop',s.lop),'ket_qua',r,'ne_nep',n,'phuc_khao',a);
end $$;

create or replace function public.portal_gui_phuc_khao(p_ma_hs text,p_mat_khau text,p_ket_qua_id bigint,p_ly_do text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare s public.danh_sach%rowtype; q public.ket_qua_kiem_tra%rowtype; new_id bigint;
begin
 select * into s from public.danh_sach d where btrim(d.ma_hs)=btrim(p_ma_hs) and btrim(coalesce(d.mat_khau,''))=btrim(coalesce(p_mat_khau,'')) and (d.trang_thai is null or lower(btrim(d.trang_thai)) not in ('inactive','nghi hoc','đã nghỉ','false','0')) limit 1;
 if not found then return jsonb_build_object('ok',false,'message','Tài khoản không hợp lệ.'); end if;
 select * into q from public.ket_qua_kiem_tra where id=p_ket_qua_id and ma_hs=s.ma_hs;
 if not found then return jsonb_build_object('ok',false,'message','Bài kiểm tra không thuộc tài khoản này.'); end if;
 if length(btrim(coalesce(p_ly_do,'')))<5 then return jsonb_build_object('ok',false,'message','Lý do phúc khảo cần ít nhất 5 ký tự.'); end if;
 insert into public.phuc_khao_kiem_tra(ket_qua_id,ma_hs,ly_do) values(q.id,s.ma_hs,btrim(p_ly_do)) returning id into new_id;
 return jsonb_build_object('ok',true,'id',new_id);
exception when unique_violation then return jsonb_build_object('ok',false,'message','Bài kiểm tra này đã có yêu cầu phúc khảo.');
end $$;

