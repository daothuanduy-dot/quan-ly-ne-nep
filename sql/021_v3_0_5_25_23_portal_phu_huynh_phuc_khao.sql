create or replace function public.qlnn_xac_nhan_admin(p_ma_cb text,p_mat_khau text)
returns boolean language sql security definer set search_path=public as $$
 select exists(select 1 from public.can_bo c where btrim(c.ma_cb)=btrim(p_ma_cb) and coalesce(c.mat_khau,'')=coalesce(p_mat_khau,'') and coalesce(c.trang_thai,true)=true and (lower(coalesce(c.vai_tro,'')) in ('admin','quản trị hệ thống') or coalesce(c.vai_tro_list,'{}'::text[]) @> array['Admin']::text[]));
$$;
create or replace function public.admin_nhap_ket_qua(p_ma_cb text,p_mat_khau text,p_rows jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare item jsonb; n int:=0; hs text; monv text; diemv numeric; roundv text;
begin
 if not public.qlnn_xac_nhan_admin(p_ma_cb,p_mat_khau) then return jsonb_build_object('ok',false,'message','Chỉ quản trị hệ thống mới được đăng tải kết quả.'); end if;
 if jsonb_typeof(p_rows)<>'array' then return jsonb_build_object('ok',false,'message','Dữ liệu tải lên không hợp lệ.'); end if;
 for item in select * from jsonb_array_elements(p_rows) loop
  hs:=nullif(btrim(item->>'ma_hs'),''); monv:=btrim(item->>'mon'); roundv:=nullif(btrim(item->>'dot_kiem_tra'),''); diemv:=nullif(item->>'diem','')::numeric;
  if hs is null or roundv is null or monv not in ('Toán','Văn','Tiếng Anh','Vật lý','Hoá học','Sinh học','Lịch Sử','Địa lý','GD KTPL','Tin học') or diemv is null or diemv<0 or diemv>10 then continue; end if;
  if not exists(select 1 from public.danh_sach d where d.ma_hs=hs) then continue; end if;
  insert into public.ket_qua_kiem_tra(ma_hs,nam_hoc,dot_kiem_tra,loai_kiem_tra,mon,diem,ngay_kiem_tra,ghi_chu)
  values(hs,coalesce(nullif(item->>'nam_hoc',''),'2026-2027'),roundv,coalesce(nullif(item->>'loai_kiem_tra',''),'Định kỳ'),monv,diemv,nullif(item->>'ngay_kiem_tra','')::date,nullif(item->>'ghi_chu',''))
  on conflict(ma_hs,dot_kiem_tra,mon,nam_hoc) do update set loai_kiem_tra=excluded.loai_kiem_tra,diem=excluded.diem,ngay_kiem_tra=excluded.ngay_kiem_tra,ghi_chu=excluded.ghi_chu,updated_at=now(); n:=n+1;
 end loop;
 return jsonb_build_object('ok',true,'count',n);
exception when others then return jsonb_build_object('ok',false,'message','Lỗi nhập kết quả: '||sqlerrm);
end $$;
create or replace function public.admin_lay_ket_qua(p_ma_cb text,p_mat_khau text)
returns jsonb language plpgsql security definer set search_path=public as $$ declare r jsonb; begin
 if not public.qlnn_xac_nhan_admin(p_ma_cb,p_mat_khau) then return jsonb_build_object('ok',false,'message','Không có quyền quản trị.'); end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.dot_kiem_tra desc,x.ma_hs,x.mon),'[]'::jsonb) into r from (select ma_hs,dot_kiem_tra,mon,diem,ngay_kiem_tra,loai_kiem_tra from public.ket_qua_kiem_tra order by dot_kiem_tra desc limit 1000) x;
 return jsonb_build_object('ok',true,'rows',r); end $$;
create or replace function public.admin_lay_phuc_khao(p_ma_cb text,p_mat_khau text)
returns jsonb language plpgsql security definer set search_path=public as $$ declare r jsonb; begin
 if not public.qlnn_xac_nhan_admin(p_ma_cb,p_mat_khau) then return jsonb_build_object('ok',false,'message','Không có quyền quản trị.'); end if;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.created_at desc),'[]'::jsonb) into r from (select p.id,p.ket_qua_id,p.ma_hs,p.ly_do,p.trang_thai,p.phan_hoi,p.created_at,q.mon,q.dot_kiem_tra,q.diem,q.id as ket_result_id from public.phuc_khao_kiem_tra p join public.ket_qua_kiem_tra q on q.id=p.ket_qua_id order by p.created_at desc limit 1000) x;
 return jsonb_build_object('ok',true,'rows',r); end $$;
create or replace function public.admin_cap_nhat_phuc_khao(p_ma_cb text,p_mat_khau text,p_id bigint,p_trang_thai text,p_phan_hoi text)
returns jsonb language plpgsql security definer set search_path=public as $$ begin
 if not public.qlnn_xac_nhan_admin(p_ma_cb,p_mat_khau) then return jsonb_build_object('ok',false,'message','Không có quyền quản trị.'); end if;
 if p_trang_thai not in ('Đã gửi','Đang xem xét','Đã xử lý','Từ chối') then return jsonb_build_object('ok',false,'message','Trạng thái không hợp lệ.'); end if;
 update public.phuc_khao_kiem_tra set trang_thai=p_trang_thai,phan_hoi=nullif(btrim(p_phan_hoi),''),updated_at=now() where id=p_id;
 if not found then return jsonb_build_object('ok',false,'message','Không tìm thấy yêu cầu phúc khảo.'); end if;
 return jsonb_build_object('ok',true); end $$;

